import { z } from "zod";

/**
 * Agent execution states
 */
export enum AgentState {
  IDLE = "IDLE",
  UNDERSTANDING = "UNDERSTANDING",
  CONTEXT_LOADING = "CONTEXT_LOADING",
  PLANNING = "PLANNING",
  EXECUTING = "EXECUTING",
  WAITING_FOR_APPROVAL = "WAITING_FOR_APPROVAL",
  VERIFYING = "VERIFYING",
  COMPLETED = "COMPLETED",
  FAILED = "FAILED",
  CANCELLED = "CANCELLED",
}

/**
 * Risk levels for tool operations
 */
export enum RiskLevel {
  READ_ONLY = "READ_ONLY",
  LOW_RISK_WRITE = "LOW_RISK_WRITE",
  CONSEQUENTIAL = "CONSEQUENTIAL",
}

/**
 * Tool definition
 */
export const ToolSchema = z.object({
  name: z.string(),
  description: z.string(),
  inputSchema: z.record(z.unknown()),
  outputSchema: z.record(z.unknown()),
  risk: z.nativeEnum(RiskLevel),
});

export type Tool = z.infer<typeof ToolSchema>;

/**
 * Tool call made by the agent
 */
export const ToolCallSchema = z.object({
  id: z.string().uuid(),
  tool: z.string(),
  arguments: z.record(z.unknown()),
  risk: z.nativeEnum(RiskLevel),
  timestamp: z.number(),
});

export type ToolCall = z.infer<typeof ToolCallSchema>;

/**
 * Result of a tool execution
 */
export const ToolResultSchema = z.object({
  callId: z.string().uuid(),
  success: z.boolean(),
  data: z.unknown().nullable(),
  error: z.string().nullable(),
  timestamp: z.number(),
});

export type ToolResult = z.infer<typeof ToolResultSchema>;

/**
 * A single step in an execution plan
 */
export const PlanStepSchema = z.object({
  id: z.string(),
  description: z.string(),
  tool: z.string(),
  risk: z.nativeEnum(RiskLevel),
  arguments: z.record(z.unknown()).optional(),
  dependsOn: z.array(z.string()).optional(),
});

export type PlanStep = z.infer<typeof PlanStepSchema>;

/**
 * Execution plan generated by the agent
 */
export const PlanSchema = z.object({
  goal: z.string(),
  steps: z.array(PlanStepSchema),
  createdAt: z.number(),
  updatedAt: z.number(),
});

export type Plan = z.infer<typeof PlanSchema>;

/**
 * Goal submitted by the user
 */
export const GoalSchema = z.object({
  id: z.string().uuid(),
  userId: z.string().uuid(),
  description: z.string(),
  context: z.record(z.unknown()).optional(),
  createdAt: z.number(),
  updatedAt: z.number(),
});

export type Goal = z.infer<typeof GoalSchema>;

/**
 * Approval request for consequential actions
 */
export const ApprovalRequestSchema = z.object({
  id: z.string().uuid(),
  executionId: z.string().uuid(),
  stepId: z.string(),
  tool: z.string(),
  arguments: z.record(z.unknown()),
  risk: z.nativeEnum(RiskLevel),
  reason: z.string(),
  createdAt: z.number(),
  expiresAt: z.number().optional(),
});

export type ApprovalRequest = z.infer<typeof ApprovalRequestSchema>;

/**
 * User's decision on an approval request
 */
export const ApprovalDecisionSchema = z.object({
  requestId: z.string().uuid(),
  approved: z.boolean(),
  decidedAt: z.number(),
  decidedBy: z.string().uuid(),
});

export type ApprovalDecision = z.infer<typeof ApprovalDecisionSchema>;

/**
 * Execution record
 */
export const ExecutionSchema = z.object({
  id: z.string().uuid(),
  goalId: z.string().uuid(),
  planId: z.string().uuid(),
  state: z.nativeEnum(AgentState),
  currentStepIndex: z.number().default(0),
  startedAt: z.number(),
  completedAt: z.number().nullable(),
  error: z.string().nullable(),
});

export type Execution = z.infer<typeof ExecutionSchema>;

/**
 * Individual step execution record
 */
export const ExecutionStepSchema = z.object({
  id: z.string().uuid(),
  executionId: z.string().uuid(),
  stepId: z.string(),
  tool: z.string(),
  risk: z.nativeEnum(RiskLevel).optional(),
  description: z.string().optional(),
  arguments: z.record(z.unknown()),
  result: ToolResultSchema.nullable(),
  status: z.enum(["pending", "running", "completed", "failed", "skipped"]),
  error: z.string().nullable().optional(),
  startedAt: z.number().nullable(),
  completedAt: z.number().nullable(),
});

export type ExecutionStep = z.infer<typeof ExecutionStepSchema>;

/**
 * Memory record for persistent context
 */
export const MemoryCategorySchema = z.enum([
  "preferences",
  "routines",
  "active_goals",
  "commitments",
  "recent_actions",
]);

export const MemoryRecordSchema = z.object({
  id: z.string().uuid(),
  userId: z.string().uuid(),
  category: MemoryCategorySchema,
  key: z.string(),
  value: z.record(z.unknown()),
  createdAt: z.number(),
  updatedAt: z.number(),
  expiresAt: z.number().nullable(),
});

export type MemoryRecord = z.infer<typeof MemoryRecordSchema>;
export type MemoryCategory = z.infer<typeof MemoryCategorySchema>;

/**
 * Agent events for timeline/UI
 */
export const AgentEventTypeSchema = z.enum([
  "understanding_started",
  "understanding_completed",
  "context_loading_started",
  "context_loading_completed",
  "planning_started",
  "planning_completed",
  "execution_started",
  "step_started",
  "step_completed",
  "step_failed",
  "approval_required",
  "approval_received",
  "verification_started",
  "verification_completed",
  "execution_completed",
  "execution_failed",
  "execution_cancelled",
]);

export const AgentEventSchema = z.object({
  id: z.string().uuid(),
  executionId: z.string().uuid(),
  type: AgentEventTypeSchema,
  message: z.string(),
  data: z.record(z.unknown()).optional(),
  timestamp: z.number(),
});

export type AgentEvent = z.infer<typeof AgentEventSchema>;
export type AgentEventType = z.infer<typeof AgentEventTypeSchema>;

/**
 * AI Provider interfaces
 */
export interface AIProvider {
  readonly name: string;
  generatePlan(input: PlanGenerationInput): Promise<Plan>;
  understandIntent(input: IntentUnderstandingInput): Promise<IntentUnderstandingOutput>;
  verifyResult(input: VerificationInput): Promise<VerificationOutput>;
}

export interface PlanGenerationInput {
  goal: string;
  context: Record<string, unknown>;
  availableTools: Tool[];
  memory: MemoryRecord[];
}

export interface IntentUnderstandingInput {
  userMessage: string;
  conversationHistory: Array<{ role: string; content: string }>;
}

export interface IntentUnderstandingOutput {
  goal: string;
  extractedEntities: Record<string, unknown>;
  confidence: number;
}

export interface VerificationInput {
  goal: string;
  plan: Plan;
  results: ToolResult[];
}

export interface VerificationOutput {
  success: boolean;
  summary: string;
  missingSteps: string[];
}

/**
 * Tool adapter interfaces
 */
export interface CalendarAdapter {
  getContext(userId: string, dateRange?: { start: Date; end: Date }): Promise<CalendarContext>;
}

export interface WeatherAdapter {
  getContext(location: string, date?: Date): Promise<WeatherContext>;
}

export interface TaskAdapter {
  getTasks(userId: string, status?: string): Promise<Task[]>;
  updateTask(taskId: string, updates: Partial<Task>): Promise<Task>;
}

export interface ShoppingAdapter {
  getList(userId: string): Promise<ShoppingList>;
  manageList(userId: string, action: "add" | "remove" | "update", items: ShoppingItem[]): Promise<ShoppingList>;
}

export interface ReminderAdapter {
  createReminder(userId: string, reminder: CreateReminderInput): Promise<Reminder>;
}

export interface UserContextAdapter {
  getContext(userId: string): Promise<UserContext>;
}

/**
 * Context data types
 */
export interface CalendarContext {
  events: CalendarEvent[];
  dateRange: { start: Date; end: Date };
}

export interface CalendarEvent {
  id: string;
  title: string;
  start: Date;
  end: Date;
  location?: string;
  attendees?: string[];
}

export interface WeatherContext {
  location: string;
  date: Date;
  forecast: WeatherForecast;
}

export interface WeatherForecast {
  temperature: { min: number; max: number; unit: "C" | "F" };
  conditions: string;
  precipitation: number;
  humidity: number;
}

export interface Task {
  id: string;
  userId: string;
  title: string;
  description?: string;
  status: "pending" | "in_progress" | "completed" | "cancelled";
  priority: "low" | "medium" | "high";
  dueDate?: Date;
  createdAt: Date;
  updatedAt: Date;
}

export interface ShoppingList {
  id: string;
  userId: string;
  items: ShoppingItem[];
  updatedAt: Date;
}

export interface ShoppingItem {
  id: string;
  name: string;
  quantity: number;
  unit?: string;
  category?: string;
  purchased: boolean;
}

export interface CreateReminderInput {
  title: string;
  description?: string;
  dueDate: Date;
  recurrence?: "none" | "daily" | "weekly" | "monthly";
}

export interface Reminder {
  id: string;
  userId: string;
  title: string;
  description?: string;
  dueDate: Date;
  recurrence: "none" | "daily" | "weekly" | "monthly";
  createdAt: Date;
}

export interface UserContext {
  userId: string;
  name?: string;
  preferences: Record<string, unknown>;
  timezone: string;
  location?: string;
}

/**
 * Utility functions
 */
export function randomUUID(): string {
  return crypto.randomUUID();
}